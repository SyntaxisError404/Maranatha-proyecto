-- ============================================================================
-- Maranatha Kids - Esquema de base de datos (PostgreSQL / Supabase)
-- ============================================================================
-- Modela: servidores (staff), salones, niños (check-in por QR) y el registro
-- del Servicio Dominical (asistencia de servidores, conteo de niños, líderes,
-- logística y otras áreas).
--
-- Ejecutar en el SQL Editor de Supabase, o con: psql -f schema.sql
-- Es idempotente: se puede volver a ejecutar sin romper nada.
-- ============================================================================

create extension if not exists pgcrypto;  -- para gen_random_uuid()

-- ----------------------------------------------------------------------------
-- SERVIDORES (staff / voluntarios)
-- ----------------------------------------------------------------------------
create table if not exists servidores (
  id              bigint primary key generated by default as identity,
  nombre          text not null,
  grupo           text not null,                       -- Maternal, Infantil, Prejuvenil, Logística Operativa, Almacén, Secretaría, Distribución Alimentos
  funcion_default text not null default 'Servidor',    -- Capitán, Mano Derecha, Servidor, Capitán Área, ...
  activo          boolean not null default true,
  created_at      timestamptz not null default now()
);

create index if not exists ix_servidores_grupo on servidores (grupo);

-- ----------------------------------------------------------------------------
-- SALONES (aulas por sección)
-- ----------------------------------------------------------------------------
create table if not exists salones (
  id      text primary key,                            -- id natural: 'cuna', 'sala1', ...
  seccion text not null,                               -- Maternal | Infantil | Prejuvenil
  clase   text,                                        -- rango de edad: '2 AÑOS', ...
  nombre  text not null,
  orden   int not null default 0
);

create index if not exists ix_salones_seccion on salones (seccion);

-- ----------------------------------------------------------------------------
-- NIÑOS (para check-in individual por QR, según la visión del README)
-- ----------------------------------------------------------------------------
create table if not exists ninos (
  id               uuid primary key default gen_random_uuid(),
  nombre           text not null,
  genero           text check (genero in ('F', 'M')),
  fecha_nacimiento date,
  representante    text,
  telefono         text,
  salon_id         text references salones(id) on delete set null,
  codigo_qr        text unique,
  activo           boolean not null default true,
  created_at       timestamptz not null default now()
);

create index if not exists ix_ninos_salon on ninos (salon_id);

-- ----------------------------------------------------------------------------
-- SERVICIOS (cabecera del registro semanal, uno por fecha)
-- ----------------------------------------------------------------------------
create table if not exists servicios (
  id            uuid primary key default gen_random_uuid(),
  fecha         date not null unique,
  realizado_por text,
  notas         text,
  cerrado       boolean not null default false,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

-- ----------------------------------------------------------------------------
-- ASISTENCIA DE SERVIDORES (por servicio): quién sirvió, en qué salón y su rol
--   - En salones: salon_id + rol ('M' maestro, 'A' auxiliar, 'C' colaborador)
--   - En logística: salon_id NULL, seccion = equipo, asistio A/I
-- ----------------------------------------------------------------------------
create table if not exists asistencia_servidores (
  id           uuid primary key default gen_random_uuid(),
  servicio_id  uuid not null references servicios(id) on delete cascade,
  servidor_id  bigint not null references servidores(id) on delete cascade,
  seccion      text not null,                          -- Maternal/Infantil/Prejuvenil o el equipo de logística
  salon_id     text references salones(id) on delete set null,
  rol          text,                                   -- 'M' | 'A' | 'C' (solo salones)
  asistio      boolean not null default true,          -- A/I (usado en logística)
  created_at   timestamptz not null default now()
);

create unique index if not exists ux_asistencia_servidores
  on asistencia_servidores (servicio_id, servidor_id, seccion, salon_id) nulls not distinct;
create index if not exists ix_asis_serv_servicio on asistencia_servidores (servicio_id);

-- ----------------------------------------------------------------------------
-- CONTEO DE NIÑOS (por servicio y salón)
-- ----------------------------------------------------------------------------
create table if not exists conteo_ninos (
  id          uuid primary key default gen_random_uuid(),
  servicio_id uuid not null references servicios(id) on delete cascade,
  salon_id    text not null references salones(id) on delete cascade,
  hembras     int not null default 0 check (hembras >= 0),
  varones     int not null default 0 check (varones >= 0),
  total       int generated always as (hembras + varones) stored,
  unique (servicio_id, salon_id)
);

-- ----------------------------------------------------------------------------
-- LÍDERES DE SECCIÓN (por servicio y sección)
-- ----------------------------------------------------------------------------
create table if not exists lideres_seccion (
  id           uuid primary key default gen_random_uuid(),
  servicio_id  uuid not null references servicios(id) on delete cascade,
  seccion      text not null,
  capitan      text,
  mano_derecha text,
  cesta_amor   text,
  unique (servicio_id, seccion)
);

-- ----------------------------------------------------------------------------
-- OTRAS ÁREAS (totales por servicio: Ujieres, Seguridad, Protocolo, ...)
-- ----------------------------------------------------------------------------
create table if not exists otras_areas (
  id          uuid primary key default gen_random_uuid(),
  servicio_id uuid not null references servicios(id) on delete cascade,
  area        text not null,
  total       int not null default 0 check (total >= 0),
  unique (servicio_id, area)
);

-- ----------------------------------------------------------------------------
-- SALONES CERRADOS (por servicio)
-- ----------------------------------------------------------------------------
create table if not exists salones_cerrados (
  servicio_id uuid not null references servicios(id) on delete cascade,
  salon_id    text not null references salones(id) on delete cascade,
  primary key (servicio_id, salon_id)
);

-- ----------------------------------------------------------------------------
-- ASISTENCIA DE NIÑOS (check-in individual por QR / entrada manual)
-- ----------------------------------------------------------------------------
create table if not exists asistencia_ninos (
  id             uuid primary key default gen_random_uuid(),
  nino_id        uuid not null references ninos(id) on delete cascade,
  servicio_id    uuid references servicios(id) on delete set null,
  salon_id       text references salones(id) on delete set null,
  hora_entrada   timestamptz not null default now(),
  hora_salida    timestamptz,
  registrado_por uuid,
  created_at     timestamptz not null default now()
);

create index if not exists ix_asis_ninos_servicio on asistencia_ninos (servicio_id);
create index if not exists ix_asis_ninos_nino     on asistencia_ninos (nino_id);

-- ============================================================================
-- ROW LEVEL SECURITY
-- Internamente la app la usan servidores autenticados. Habilitamos RLS en
-- todas las tablas y damos acceso completo solo a usuarios autenticados.
-- (Ajustar a roles más finos cuando se definan permisos por ministerio.)
-- ============================================================================
do $$
declare
  t text;
  tablas text[] := array[
    'servidores', 'salones', 'ninos', 'servicios', 'asistencia_servidores',
    'conteo_ninos', 'lideres_seccion', 'otras_areas', 'salones_cerrados',
    'asistencia_ninos'
  ];
begin
  foreach t in array tablas loop
    execute format('alter table %I enable row level security;', t);
    execute format('drop policy if exists "acceso_autenticados" on %I;', t);
    execute format(
      'create policy "acceso_autenticados" on %I for all to authenticated using (true) with check (true);',
      t
    );
  end loop;
end $$;
